#!/usr/bin/env bash
# Write THIRD-PARTY-NOTICES.md: what Berth.app ships that isn't Berth's own
# code, and under which license. The Rust crates are those compiled into the
# app for macOS (`cargo tree -e normal`), the npm packages those bundled into
# the sidecar (`pnpm licenses --prod`). Run again after changing dependencies.
set -euo pipefail
cd "$(dirname "$0")/.."

out=THIRD-PARTY-NOTICES.md
sdk=$(node -p 'require("./sidecar/package.json").dependencies["@anthropic-ai/claude-agent-sdk"]')

{
  cat <<EOF
# Third-party notices

Berth's own code is under the MIT License ([LICENSE](LICENSE)). Berth.app also
ships the software below, each under its own terms. Generated by
\`scripts/notices.sh\`.

## Not open source

- **Claude Agent SDK** (\`@anthropic-ai/claude-agent-sdk\` $sdk), bundled into
  \`Contents/Resources/sidecar/sidecar.mjs\`, and the **Claude Code** binary it
  carries (\`Contents/Resources/sidecar/claude\`): © Anthropic PBC, all rights
  reserved. Use is subject to Anthropic's terms:
  <https://code.claude.com/docs/en/legal-and-compliance>.

## Fonts, icons and connector CLIs

| What | License | Text |
|---|---|---|
| IBM Plex Sans | SIL Open Font License 1.1 | \`crates/berth-app/assets/fonts/OFL-IBMPlex.txt\` |
| JetBrains Mono | SIL Open Font License 1.1 | \`crates/berth-app/assets/fonts/OFL-JetBrainsMono.txt\` |
| Lucide icons | ISC | \`crates/berth-app/assets/icons/berth/LICENSE-LUCIDE\` |
| linear-cli | MIT | \`connectors/linear/LICENSE-linear-cli\` |
| posthog-cli | MIT | \`connectors/posthog/LICENSE-posthog-cli\` |

## npm packages in the sidecar

| Package | Version | License |
|---|---|---|
EOF
  (cd sidecar && pnpm licenses list --prod --json) | node -e '
    const d = JSON.parse(require("fs").readFileSync(0, "utf8"));
    const rows = [];
    for (const [license, pkgs] of Object.entries(d))
      for (const p of pkgs) {
        if (p.name === "@anthropic-ai/claude-agent-sdk") continue;
        rows.push([p.name, (p.versions ?? [p.version]).join(", "), license]);
      }
    rows.sort((a, b) => a[0].localeCompare(b[0]));
    for (const r of rows) console.log(`| ${r.join(" | ")} |`);
  '
  cat <<'EOF'

## Rust crates compiled into the app

`option-ext` (MPL-2.0) is used unmodified; its source is on crates.io.
`tree-sitter-graphql` names no license in its manifest; its LICENSE file is
MIT.

| Crate | Version | License |
|---|---|---|
EOF
  cargo tree -p berth-app -e normal --target aarch64-apple-darwin --prefix none \
    --format '{p}|{l}' --offline \
    | sed -e 's/ (\*)//' -e 's/ (proc-macro)//' \
    | grep -v '^berth-' | sort -u \
    | awk -F'|' '{ split($1, a, " v"); l = $2 == "" ? "see its LICENSE" : $2; print "| " a[1] " | " a[2] " | " l " |" }'
} > "$out"

echo "wrote $out"
